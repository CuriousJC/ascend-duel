func main() {
	dir := flag.String("dir", filepath.FromSlash(root),
		"directory to write the sheets and the index into")
	indexOnly := flag.Bool("index", false, "rewrite the index without regenerating the sheets")
	flag.Parse()

	if err := run(*dir, *indexOnly); err != nil {
		log.Fatal(err)
	}
}

func run(dir string, indexOnly bool) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("making %s: %w", dir, err)
	}

	var failed []string
	if !indexOnly {
		for _, s := range sheets {
			fmt.Printf("== %s\n", s.Tool)
			out, err := exec.Command("go", "run", s.Tool, "-dir", filepath.Join(dir, s.Dir)).CombinedOutput()
			os.Stdout.Write(out)
			if err != nil {
				// Reported and carried on: see the package comment. A half-written directory under a
				// complete index is the failure this avoids.
				failed = append(failed, s.Tool)
			}
		}
	}

	out := filepath.Join(dir, "index.html")
	f, err := os.Create(out)
	if err != nil {
		return fmt.Errorf("creating %s: %w", out, err)
	}
	defer f.Close()

	if err := tmpl.Execute(f, index{Sheets: sheets, Glyphs: glyphs}); err != nil {
		return fmt.Errorf("writing %s: %w", out, err)
	}
	fmt.Printf("\nwrote %s\n", out)

	if len(failed) > 0 {
		return fmt.Errorf("these sheets failed and are now stale: %s", strings.Join(failed, ", "))
	}
	return nil
}

type sheet struct {
	Dir   string
	Tool  string
	Title string
	Blurb string
}

// Href is where the index links, which is the sheet's own page rather than its directory: a
// directory link lands on whatever the host decides to serve, and a file:// clone decides on a
// listing.
func (s sheet) Href() string { return s.Dir + "/index.html" }

type link struct {
	Title string
	Href  string
	Blurb string
}

type index struct {
	Sheets []sheet
	Glyphs link
}

